package eleeter.unifystudiox.ui.framework.layout;


public enum Alignment
{
    /** Align to the start of the axis */
    START,

    /** Align to the center of the axis */
    CENTER,

    /** Align to the end of the axis */
    END,

    /** Stretch to fill the available space */
    STRETCH,

    /** Distribute space evenly between children */
    SPACE_BETWEEN,

    /** Distribute space evenly around children */
    SPACE_AROUND
}
